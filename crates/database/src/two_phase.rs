/// Globally unique transaction ID for 2PC.
/// Generated by the coordinator using UUID v4.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct TwoPhaseTransactionId(pub String);

impl TwoPhaseTransactionId {
    pub fn new() -> Self {
        Self(uuid::Uuid::new_v4().to_string())
    }
}

impl std::fmt::Display for TwoPhaseTransactionId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// State of a 2PC transaction stored in NATS KV.
/// This is the commit decision record — the point of no return.
/// Follows Vitess's Metadata Manager (MM) pattern.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum TwoPhaseDecision {
    /// All participants prepared successfully. Commit.
    Committed {
        commit_ts: u64,
        participants: Vec<u32>,
        #[serde(default)]
        resolved_participants: Vec<u32>,
    },
    /// A participant failed to prepare, or coordinator timed out. Rollback.
    RolledBack {
        reason: String,
        participants: Vec<u32>,
        #[serde(default)]
        resolved_participants: Vec<u32>,
    },
}

impl TwoPhaseDecision {
    pub fn committed(commit_ts: u64, participants: Vec<u32>) -> Self {
        Self::Committed {
            commit_ts,
            participants,
            resolved_participants: Vec::new(),
        }
    }

    pub fn rolled_back(reason: String, participants: Vec<u32>) -> Self {
        Self::RolledBack {
            reason,
            participants,
            resolved_participants: Vec::new(),
        }
    }

    pub fn participants(&self) -> &[u32] {
        match self {
            Self::Committed { participants, .. } | Self::RolledBack { participants, .. } => {
                participants
            },
        }
    }

    pub fn resolved_participants(&self) -> &[u32] {
        match self {
            Self::Committed {
                resolved_participants,
                ..
            }
            | Self::RolledBack {
                resolved_participants,
                ..
            } => resolved_participants,
        }
    }

    pub fn mark_participant_resolved(&mut self, participant: PartitionId) {
        let resolved = match self {
            Self::Committed {
                resolved_participants,
                ..
            }
            | Self::RolledBack {
                resolved_participants,
                ..
            } => resolved_participants,
        };
        if !resolved.contains(&participant.0) {
            resolved.push(participant.0);
            resolved.sort_unstable();
            resolved.dedup();
        }
    }

    pub fn all_participants_resolved(&self) -> bool {
        self.participants()
            .iter()
            .all(|participant| self.resolved_participants().contains(participant))
    }
}

/// Result from a successful Prepare on a participant.
#[derive(Debug)]
pub struct PrepareResult {
    /// The timestamp assigned to this partition's portion of the transaction.
    pub prepare_ts: Timestamp,
}

/// Redo log entry persisted during Prepare for crash recovery.
/// If a node crashes after Prepare but before CommitPrepared/RollbackPrepared,
/// the transaction watcher reads the redo log and resolves the transaction
/// by checking the decision record in NATS KV.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TwoPhaseRedoEntry {
    pub transaction_id: String,
    pub prepare_ts: u64,
    pub partition_id: u32,
    #[serde(default)]
    pub participants: Vec<u32>,
    #[serde(default)]
    pub prepared_at_unix_millis: Option<u64>,
    pub write_source: Option<String>,
    pub participant_transaction_hex: String,
}

impl TwoPhaseRedoEntry {
    pub fn new(
        transaction_id: &TwoPhaseTransactionId,
        prepare_ts: Timestamp,
        partition_id: PartitionId,
        transaction: ParticipantTransaction,
        write_source: &WriteSource,
    ) -> anyhow::Result<Self> {
        Self::new_with_participants(
            transaction_id,
            prepare_ts,
            partition_id,
            &[partition_id],
            transaction,
            write_source,
        )
    }

    pub fn new_with_participants(
        transaction_id: &TwoPhaseTransactionId,
        prepare_ts: Timestamp,
        partition_id: PartitionId,
        participants: &[PartitionId],
        transaction: ParticipantTransaction,
        write_source: &WriteSource,
    ) -> anyhow::Result<Self> {
        let proto = TwoPcParticipantTransactionProto::try_from(transaction)?;
        let mut bytes = Vec::new();
        proto
            .encode(&mut bytes)
            .context("2PC: Failed to encode participant transaction redo")?;
        Ok(Self {
            transaction_id: transaction_id.0.clone(),
            prepare_ts: u64::from(prepare_ts),
            partition_id: partition_id.0,
            participants: participants.iter().map(|partition| partition.0).collect(),
            prepared_at_unix_millis: Some(now_unix_millis()),
            write_source: write_source.as_str().map(str::to_string),
            participant_transaction_hex: hex::encode(bytes),
        })
    }

    pub fn transaction_id(&self) -> TwoPhaseTransactionId {
        TwoPhaseTransactionId(self.transaction_id.clone())
    }

    pub fn prepare_ts(&self) -> anyhow::Result<Timestamp> {
        self.prepare_ts.try_into()
    }

    pub fn partition_id(&self) -> PartitionId {
        PartitionId(self.partition_id)
    }

    pub fn participants(&self) -> Vec<PartitionId> {
        if self.participants.is_empty() {
            vec![self.partition_id()]
        } else {
            self.participants.iter().copied().map(PartitionId).collect()
        }
    }

    pub fn prepare_age(&self) -> Option<Duration> {
        let prepared_at = self.prepared_at_unix_millis?;
        let now = now_unix_millis();
        Some(Duration::from_millis(now.saturating_sub(prepared_at)))
    }

    pub fn prepare_timed_out(&self, timeout: Duration) -> bool {
        self.prepare_age().is_some_and(|age| age >= timeout)
    }

    pub fn write_source(&self) -> WriteSource {
        WriteSource::from(self.write_source.clone())
    }

    pub fn participant_transaction(&self) -> anyhow::Result<ParticipantTransaction> {
        let bytes = hex::decode(&self.participant_transaction_hex)
            .context("2PC: Failed to decode participant transaction redo")?;
        let proto = TwoPcParticipantTransactionProto::decode(bytes.as_slice())
            .context("2PC: Failed to parse participant transaction redo")?;
        ParticipantTransaction::try_from(proto)
    }
}

fn now_unix_millis() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis()
        .try_into()
        .unwrap_or(u64::MAX)
}

