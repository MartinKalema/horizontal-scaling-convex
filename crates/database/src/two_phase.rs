impl TryFrom<TwoPcParticipantTransactionProto> for ParticipantTransaction {
    type Error = anyhow::Error;

    fn try_from(value: TwoPcParticipantTransactionProto) -> anyhow::Result<Self> {
        let begin_timestamp = value
            .begin_timestamp
            .context("TwoPcParticipantTransaction missing begin_timestamp")?
            .try_into()?;

        let tablet_metadata = value
            .tablet_metadata
            .into_iter()
            .map(
                |TwoPcTabletMetadata {
                     tablet_id,
                     component_id,
                     table_number,
                     table_name,
                 }| {
                    let tablet_id = tablet_id_from_bytes(tablet_id)?;
                    let namespace = match component_id {
                        Some(component_id) => TableNamespace::ByComponent(component_id.parse()?),
                        None => TableNamespace::Global,
                    };
                    let table_number = table_number.try_into()?;
                    let table_name = table_name.parse::<TableName>()?;
                    Ok((
                        tablet_id,
                        ParticipantTabletMetadata {
                            tablet_id,
                            namespace,
                            table_number,
                            table_name,
                        },
                    ))
                },
            )
            .collect::<anyhow::Result<BTreeMap<_, _>>>()?;

        let indexed_reads = value
            .indexed_reads
            .into_iter()
            .map(
                |TwoPcIndexedRead {
                     tablet_id,
                     descriptor,
                     fields,
                     intervals,
                 }| {
                    let tablet_id = tablet_id_from_bytes(tablet_id)?;
                    let index_name = descriptor_to_index_name(tablet_id, descriptor)?;
                    let fields = fields
                        .into_iter()
                        .map(FieldPath::try_from)
                        .collect::<anyhow::Result<Vec<_>>>()?;
                    let intervals = IntervalSet::try_from(intervals)?;
                    Ok((
                        index_name,
                        IndexReads {
                            fields: IndexedFields::try_from(fields)?,
                            intervals,
                            stack_traces: None,
                        },
                    ))
                },
            )
            .collect::<anyhow::Result<BTreeMap<_, _>>>()?;

        let search_reads = value
            .search_reads
            .into_iter()
            .map(
                |TwoPcSearchRead {
                     tablet_id,
                     descriptor,
                     text_queries,
                     filter_conditions,
                 }| {
                    let tablet_id = tablet_id_from_bytes(tablet_id)?;
                    let index_name = descriptor_to_index_name(tablet_id, descriptor)?;
                    let text_queries = text_queries
                        .into_iter()
                        .map(
                            |TwoPcTextQueryTermRead { field_path, term }| -> anyhow::Result<_> {
                                let field_path = field_path
                                    .context("TwoPcTextQueryTermRead missing field_path")?
                                    .try_into()?;
                                let term = text_query_term_from_proto(
                                    term.context("TwoPcTextQueryTermRead missing term")?,
                                )?;
                                Ok(TextQueryTermRead::new(field_path, term))
                            },
                        )
                        .collect::<anyhow::Result<Vec<_>>>()?;
                    let filter_conditions = filter_conditions
                        .into_iter()
                        .map(
                            |TwoPcFilterConditionRead { field_path, value }| -> anyhow::Result<_> {
                                let field_path = field_path
                                    .context("TwoPcFilterConditionRead missing field_path")?
                                    .try_into()?;
                                Ok(FilterConditionRead::Must(
                                    field_path,
                                    FilterValue::from(value),
                                ))
                            },
                        )
                        .collect::<anyhow::Result<Vec<_>>>()?;
                    Ok((
                        index_name,
                        QueryReads::new(text_queries.into(), filter_conditions.into()),
                    ))
                },
            )
            .collect::<anyhow::Result<BTreeMap<_, _>>>()?;

        let writes = value
            .writes
            .into_iter()
            .map(DocumentUpdateWithPrevTs::try_from)
            .collect::<anyhow::Result<Vec<_>>>()?;

        Ok(Self {
            begin_timestamp,
            tablet_metadata,
            reads: ReadSet::new(indexed_reads, search_reads),
            writes,
        })
    }
}

impl TryFrom<ParticipantTransaction> for TwoPcParticipantTransactionProto {
    type Error = anyhow::Error;

    fn try_from(value: ParticipantTransaction) -> anyhow::Result<Self> {
        let indexed_reads = value
            .reads
            .iter_indexed()
            .map(|(index_name, reads)| TwoPcIndexedRead {
                tablet_id: tablet_id_to_bytes(*index_name.table()),
                descriptor: index_name.descriptor().to_string(),
                fields: Vec::<pb::common::FieldPath>::from(reads.fields.clone()),
                intervals: reads.intervals.clone().into(),
            })
            .collect();

        let search_reads = value
            .reads
            .iter_search()
            .map(|(index_name, reads)| -> anyhow::Result<TwoPcSearchRead> {
                Ok(TwoPcSearchRead {
                    tablet_id: tablet_id_to_bytes(*index_name.table()),
                    descriptor: index_name.descriptor().to_string(),
                    text_queries: reads
                        .text_queries
                        .iter()
                        .map(|read| {
                            Ok(TwoPcTextQueryTermRead {
                                field_path: Some(read.field_path.clone().into()),
                                term: Some(text_query_term_to_proto(read.term.clone())),
                            })
                        })
                        .collect::<anyhow::Result<Vec<_>>>()?,
                    filter_conditions: reads
                        .filter_conditions
                        .iter()
                        .map(|read| match read {
                            FilterConditionRead::Must(field_path, value) => {
                                Ok(TwoPcFilterConditionRead {
                                    field_path: Some(field_path.clone().into()),
                                    value: value.clone().into(),
                                })
                            },
                        })
                        .collect::<anyhow::Result<Vec<_>>>()?,
                })
            })
            .collect::<anyhow::Result<Vec<_>>>()?;

        let writes = value
            .writes
            .into_iter()
            .map(pb::common::DocumentUpdateWithPrevTs::try_from)
            .collect::<anyhow::Result<Vec<_>>>()?;

        Ok(TwoPcParticipantTransactionProto {
            begin_timestamp: Some(RepeatableTimestampProto::from(value.begin_timestamp)),
            tablet_metadata: value
                .tablet_metadata
                .into_values()
                .map(|metadata| TwoPcTabletMetadata {
                    tablet_id: tablet_id_to_bytes(metadata.tablet_id),
                    component_id: match metadata.namespace {
                        TableNamespace::Global => None,
                        TableNamespace::ByComponent(component_id) => Some(component_id.encode()),
                    },
                    table_number: u32::from(metadata.table_number),
                    table_name: metadata.table_name.to_string(),
                })
                .collect(),
            indexed_reads,
            search_reads,
            writes,
        })
    }
}

fn text_query_term_from_proto(value: searchlight::TextQueryTerm) -> anyhow::Result<TextQueryTerm> {
    match value.term_type {
        Some(searchlight::text_query_term::TermType::Exact(exact)) => {
            Ok(TextQueryTerm::Exact(exact.token))
        },
        Some(searchlight::text_query_term::TermType::Fuzzy(fuzzy)) => Ok(TextQueryTerm::Fuzzy {
            token: fuzzy.token,
            max_distance: FuzzyDistance::try_from(fuzzy.max_distance as u8)?,
            prefix: fuzzy.prefix,
        }),
        None => anyhow::bail!("TextQueryTerm missing term_type"),
    }
}

fn text_query_term_to_proto(value: TextQueryTerm) -> searchlight::TextQueryTerm {
    let term_type = match value {
        TextQueryTerm::Exact(token) => {
            searchlight::text_query_term::TermType::Exact(searchlight::ExactTextTerm { token })
        },
        TextQueryTerm::Fuzzy {
            token,
            max_distance,
            prefix,
        } => searchlight::text_query_term::TermType::Fuzzy(searchlight::FuzzyTextTerm {
            token,
            max_distance: u8::from(max_distance) as u32,
            prefix,
        }),
    };
    searchlight::TextQueryTerm {
        term_type: Some(term_type),
    }
}

/// gRPC client for reaching remote partitions' 2PC service.
pub struct TwoPhaseCommitGrpcClient {
    client: TonicTwoPcClient<Channel>,
    cluster_auth: Option<ClusterGrpcAuth>,
}

fn normalize_grpc_addr(addr: &str) -> String {
    if addr.contains("://") {
        addr.to_string()
    } else {
        format!("http://{addr}")
    }
}

#[derive(Clone)]
pub struct TwoPhaseCommitGrpcClientPool {
    cluster_auth: Option<ClusterGrpcAuth>,
    clients: Arc<Mutex<BTreeMap<String, Arc<TwoPhaseCommitGrpcClient>>>>,
}

impl TwoPhaseCommitGrpcClientPool {
    pub fn new(cluster_auth: Option<ClusterGrpcAuth>) -> Self {
        Self {
            cluster_auth,
            clients: Arc::new(Mutex::new(BTreeMap::new())),
        }
    }

    pub async fn client(&self, addr: &str) -> anyhow::Result<Arc<TwoPhaseCommitGrpcClient>> {
        let normalized_addr = normalize_grpc_addr(addr);
        if let Some(client) = self.clients.lock().await.get(&normalized_addr).cloned() {
            return Ok(client);
        }

        let client = Arc::new(
            TwoPhaseCommitGrpcClient::connect_inner(&normalized_addr, self.cluster_auth.clone())
                .await?,
        );
        let mut clients = self.clients.lock().await;
        Ok(clients
            .entry(normalized_addr)
            .or_insert_with(|| client.clone())
            .clone())
    }
}

impl TwoPhaseCommitGrpcClient {
    pub async fn connect(addr: &str) -> anyhow::Result<Self> {
        Self::connect_inner(addr, None).await
    }

    pub async fn connect_with_auth(
        addr: &str,
        cluster_auth: ClusterGrpcAuth,
    ) -> anyhow::Result<Self> {
        Self::connect_inner(addr, Some(cluster_auth)).await
    }

    async fn connect_inner(
        addr: &str,
        cluster_auth: Option<ClusterGrpcAuth>,
    ) -> anyhow::Result<Self> {
        let normalized_addr = normalize_grpc_addr(addr);
        let client = TonicTwoPcClient::connect(normalized_addr.clone())
            .await
            .with_context(|| format!("Failed to connect to 2PC service at {normalized_addr}"))?;
        Ok(Self {
            client,
            cluster_auth,
        })
    }

    fn request<T>(&self, message: T) -> Request<T> {
        match &self.cluster_auth {
            Some(auth) => auth.request(message),
            None => Request::new(message),
        }
    }

    pub async fn prepare(
        &self,
        transaction_id: &TwoPhaseTransactionId,
        transaction: ParticipantTransaction,
        write_source: WriteSource,
        prepare_ts: Timestamp,
        placement_version: crate::partition::PlacementVersion,
        participants: &[PartitionId],
    ) -> anyhow::Result<PrepareResult> {
        let request = TwoPcPrepareRequest {
            transaction_id: transaction_id.0.clone(),
            transaction: Some(transaction.try_into()?),
            write_source: write_source.as_str().unwrap_or_default().to_string(),
            prepare_ts: u64::from(prepare_ts),
            placement_version: u64::from(placement_version),
            participants: participants.iter().map(|partition| partition.0).collect(),
        };
        let response = self
            .client
            .clone()
            .prepare(self.request(request))
            .await
            .context("gRPC Prepare failed")?;
        let TwoPcPrepareResponse { prepare_ts } = response.into_inner();
        Ok(PrepareResult {
            prepare_ts: prepare_ts.try_into()?,
        })
    }

    pub async fn commit_prepared(
        &self,
        transaction_id: &TwoPhaseTransactionId,
    ) -> anyhow::Result<u64> {
        let request = TwoPcCommitRequest {
            transaction_id: transaction_id.0.clone(),
        };
        let response = self
            .client
            .clone()
            .commit_prepared(self.request(request))
            .await
            .context("gRPC CommitPrepared failed")?;
        Ok(response.into_inner().commit_ts)
    }

    pub async fn rollback_prepared(
        &self,
        transaction_id: &TwoPhaseTransactionId,
    ) -> anyhow::Result<()> {
        let request = TwoPcRollbackRequest {
            transaction_id: transaction_id.0.clone(),
        };
        self.client
            .clone()
            .rollback_prepared(self.request(request))
            .await
            .context("gRPC RollbackPrepared failed")?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_node_addresses_parsing() {
        let addrs = NodeAddresses::from_config("0=node-a:50051,1=node-b:50051");
        assert_eq!(addrs.address_for(PartitionId(0)), Some("node-a:50051"));
        assert_eq!(addrs.address_for(PartitionId(1)), Some("node-b:50051"));
        assert_eq!(addrs.address_for(PartitionId(2)), None);
    }

    #[test]
    fn test_node_addresses_empty() {
        let addrs = NodeAddresses::from_config("");
        assert!(addrs.partitions().is_empty());
    }

    #[test]
    fn test_two_phase_transaction_id() {
        let id1 = TwoPhaseTransactionId::new();
        let id2 = TwoPhaseTransactionId::new();
        assert_ne!(id1, id2);
    }

    #[test]
    fn test_decision_serialization() {
        let mut decision = TwoPhaseDecision::committed(12345, vec![0, 1]);
        decision.mark_participant_resolved(PartitionId(0));
        let json = serde_json::to_string(&decision).unwrap();
        let back: TwoPhaseDecision = serde_json::from_str(&json).unwrap();
        match back {
            TwoPhaseDecision::Committed {
                commit_ts,
                participants,
                resolved_participants,
            } => {
                assert_eq!(commit_ts, 12345);
                assert_eq!(participants, vec![0, 1]);
                assert_eq!(resolved_participants, vec![0]);
            },
            _ => panic!("Wrong variant"),
        }
    }
}
