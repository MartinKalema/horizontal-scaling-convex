#[derive(Clone, Debug)]
#[cfg_attr(any(test, feature = "testing"), derive(PartialEq))]
pub struct ParticipantTransaction {
    pub begin_timestamp: RepeatableTimestamp,
    pub tablet_metadata: BTreeMap<TabletId, ParticipantTabletMetadata>,
    pub reads: ReadSet,
    pub writes: Vec<DocumentUpdateWithPrevTs>,
}

impl ParticipantTransaction {
    pub fn from_final_transaction(
        transaction: &FinalTransaction,
        participant: PartitionId,
        write_indexes: &[usize],
        partition_map: &PartitionMap,
        write_source: &WriteSource,
    ) -> anyhow::Result<Self> {
        let selected_writes: Vec<_> = transaction
            .writes
            .coalesced_writes()
            .enumerate()
            .filter(|(index, _)| write_indexes.contains(index))
            .map(|(_, write)| write.clone())
            .collect();

        let belongs_to_participant = |tablet_id: TabletId| -> bool {
            let Ok(table_name) = transaction.table_mapping.tablet_name(tablet_id) else {
                return false;
            };
            match routed_partition_for_table(&table_name, partition_map, write_source) {
                Some(owner) => owner == participant,
                None => participant == partition_map.local_partition(),
            }
        };

        let indexed_reads = transaction
            .reads
            .read_set()
            .iter_indexed()
            .filter(|(index_name, _)| belongs_to_participant(*index_name.table()))
            .map(|(index_name, reads)| (index_name.clone(), reads.clone()))
            .collect();
        let search_reads = transaction
            .reads
            .read_set()
            .iter_search()
            .filter(|(index_name, _)| belongs_to_participant(*index_name.table()))
            .map(|(index_name, reads)| (index_name.clone(), reads.clone()))
            .collect();
        let reads = ReadSet::new(indexed_reads, search_reads);

        let mut tablet_metadata = BTreeMap::new();
        let mut record_tablet = |tablet_id: TabletId| -> anyhow::Result<()> {
            if tablet_metadata.contains_key(&tablet_id) {
                return Ok(());
            }
            let table_name = transaction.table_mapping.tablet_name(tablet_id)?;
            let table_number = transaction.table_mapping.tablet_number(tablet_id)?;
            let namespace = transaction.table_mapping.tablet_namespace(tablet_id)?;
            tablet_metadata.insert(
                tablet_id,
                ParticipantTabletMetadata {
                    tablet_id,
                    namespace,
                    table_number,
                    table_name,
                },
            );
            Ok(())
        };

        for (index_name, _) in reads.iter_indexed() {
            record_tablet(*index_name.table())?;
        }
        for (index_name, _) in reads.iter_search() {
            record_tablet(*index_name.table())?;
        }
        for write in &selected_writes {
            record_tablet(write.id.tablet_id)?;
        }

        Ok(Self {
            begin_timestamp: transaction.begin_timestamp,
            tablet_metadata,
            reads,
            writes: selected_writes,
        })
    }

    pub fn from_entire_final_transaction(transaction: &FinalTransaction) -> anyhow::Result<Self> {
        let selected_writes: Vec<_> = transaction.writes.coalesced_writes().cloned().collect();
        let mut tablet_metadata = BTreeMap::new();
        let mut record_tablet = |tablet_id: TabletId| -> anyhow::Result<()> {
            if tablet_metadata.contains_key(&tablet_id) {
                return Ok(());
            }
            let table_name = transaction.table_mapping.tablet_name(tablet_id)?;
            let table_number = transaction.table_mapping.tablet_number(tablet_id)?;
            let namespace = transaction.table_mapping.tablet_namespace(tablet_id)?;
            tablet_metadata.insert(
                tablet_id,
                ParticipantTabletMetadata {
                    tablet_id,
                    namespace,
                    table_number,
                    table_name,
                },
            );
            Ok(())
        };

        for (index_name, _) in transaction.reads.read_set().iter_indexed() {
            record_tablet(*index_name.table())?;
        }
        for (index_name, _) in transaction.reads.read_set().iter_search() {
            record_tablet(*index_name.table())?;
        }
        for write in &selected_writes {
            record_tablet(write.id.tablet_id)?;
        }

        Ok(Self {
            begin_timestamp: transaction.begin_timestamp,
            tablet_metadata,
            reads: transaction.reads.read_set().clone(),
            writes: selected_writes,
        })
    }

    pub fn augment_table_mapping(
        &self,
        table_mapping: &mut value::TableMapping,
    ) -> anyhow::Result<()> {
        for metadata in self.tablet_metadata.values() {
            if table_mapping.tablet_id_exists(metadata.tablet_id) {
                continue;
            }
            table_mapping.insert_tablet(
                metadata.tablet_id,
                metadata.namespace,
                metadata.table_number,
                metadata.table_name.clone(),
            );
        }
        Ok(())
    }
}

fn descriptor_to_index_name(
    tablet_id: TabletId,
    descriptor: String,
) -> anyhow::Result<TabletIndexName> {
    match descriptor.as_str() {
        "by_id" => Ok(TabletIndexName::by_id(tablet_id)),
        "by_creation_time" => Ok(TabletIndexName::by_creation_time(tablet_id)),
        _ => TabletIndexName::new(tablet_id, IndexDescriptor::new(descriptor)?),
    }
}

