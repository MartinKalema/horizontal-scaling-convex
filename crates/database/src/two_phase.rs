#[derive(Clone)]
pub struct NatsTwoPhaseDecisionLog {
    kv: Store,
}

impl NatsTwoPhaseDecisionLog {
    pub async fn connect(nats_url: &str) -> anyhow::Result<Self> {
        let _ = rustls::crypto::ring::default_provider().install_default();
        let client = async_nats::connect(nats_url)
            .await
            .with_context(|| format!("2PC: Failed to connect to NATS at {nats_url}"))?;
        let jetstream = async_nats::jetstream::new(client);
        let kv = jetstream
            .create_key_value(async_nats::jetstream::kv::Config {
                bucket: TWO_PHASE_KV_BUCKET.to_string(),
                history: 1,
                ..Default::default()
            })
            .await
            .context("2PC: Failed to create decision KV bucket")?;
        Ok(Self { kv })
    }
}

#[async_trait]
impl TwoPhaseDecisionLog for NatsTwoPhaseDecisionLog {
    async fn write_decision(
        &self,
        transaction_id: &TwoPhaseTransactionId,
        decision: &TwoPhaseDecision,
    ) -> anyhow::Result<()> {
        let payload = serde_json::to_vec(decision)
            .with_context(|| format!("2PC: Failed to serialize decision for {transaction_id}"))?;
        self.kv
            .put(two_phase_decision_key(transaction_id), payload.into())
            .await
            .with_context(|| format!("2PC: Failed to write decision for {transaction_id}"))?;
        Ok(())
    }

    async fn write_decision_if_absent(
        &self,
        transaction_id: &TwoPhaseTransactionId,
        decision: &TwoPhaseDecision,
    ) -> anyhow::Result<bool> {
        let payload = serde_json::to_vec(decision)
            .with_context(|| format!("2PC: Failed to serialize decision for {transaction_id}"))?;
        match self
            .kv
            .create(two_phase_decision_key(transaction_id), payload.into())
            .await
        {
            Ok(_) => Ok(true),
            Err(_) => Ok(false),
        }
    }

    async fn get_decision(
        &self,
        transaction_id: &TwoPhaseTransactionId,
    ) -> anyhow::Result<Option<TwoPhaseDecision>> {
        let Some(entry) = self
            .kv
            .entry(two_phase_decision_key(transaction_id))
            .await
            .with_context(|| format!("2PC: Failed to read decision for {transaction_id}"))?
        else {
            return Ok(None);
        };
        serde_json::from_slice(&entry.value)
            .with_context(|| format!("2PC: Failed to parse decision for {transaction_id}"))
            .map(Some)
    }

    async fn mark_participant_resolved(
        &self,
        transaction_id: &TwoPhaseTransactionId,
        participant: PartitionId,
    ) -> anyhow::Result<Option<TwoPhaseDecision>> {
        let key = two_phase_decision_key(transaction_id);
        for _ in 0..10 {
            let Some(entry) =
                self.kv.entry(key.clone()).await.with_context(|| {
                    format!("2PC: Failed to read decision for {transaction_id}")
                })?
            else {
                return Ok(None);
            };
            let mut decision: TwoPhaseDecision = serde_json::from_slice(&entry.value)
                .with_context(|| format!("2PC: Failed to parse decision for {transaction_id}"))?;
            decision.mark_participant_resolved(participant);
            let payload = serde_json::to_vec(&decision).with_context(|| {
                format!("2PC: Failed to serialize decision for {transaction_id}")
            })?;
            match self
                .kv
                .update(key.clone(), payload.into(), entry.revision)
                .await
            {
                Ok(_) => return Ok(Some(decision)),
                Err(err)
                    if err.kind()
                        == async_nats::jetstream::kv::UpdateErrorKind::WrongLastRevision =>
                {
                    continue;
                },
                Err(err) => {
                    anyhow::bail!(
                        "2PC: Failed to mark {participant} resolved for {transaction_id}: {err:#}"
                    );
                },
            }
        }
        anyhow::bail!(
            "2PC: Failed to mark {participant} resolved for {transaction_id} after CAS retries"
        )
    }

    async fn delete_decision(&self, transaction_id: &TwoPhaseTransactionId) -> anyhow::Result<()> {
        self.kv
            .delete(two_phase_decision_key(transaction_id))
            .await
            .with_context(|| format!("2PC: Failed to delete decision for {transaction_id}"))?;
        Ok(())
    }
}

/// Partition-to-address mapping for gRPC communication.
/// Each entry maps a partition ID to the gRPC address of its owner node.
#[derive(Clone, Debug)]
pub struct NodeAddresses {
    addresses: BTreeMap<PartitionId, String>,
}

impl NodeAddresses {
    /// Parse from config string: "0=host:port,1=host:port"
    pub fn from_config(config: &str) -> Self {
        let mut addresses = BTreeMap::new();
        if !config.is_empty() {
            for pair in config.split(',') {
                let pair = pair.trim();
                if let Some((id, addr)) = pair.split_once('=') {
                    if let Ok(partition_id) = id.trim().parse::<u32>() {
                        addresses.insert(PartitionId(partition_id), addr.trim().to_string());
                    }
                }
            }
        }
        Self { addresses }
    }

    /// Get the gRPC address for a partition.
    pub fn address_for(&self, partition: PartitionId) -> Option<&str> {
        self.addresses.get(&partition).map(|s| s.as_str())
    }

    /// Get all known partitions.
    pub fn partitions(&self) -> Vec<PartitionId> {
        self.addresses.keys().copied().collect()
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
